/* Lab4 自测一：两个 CPU 密集进程的输出应在时钟抢占下交错。 */
#include "kernel/types.h"              /* 引入用户程序使用的整数类型。 */
#include "user/user.h"                 /* 引入 fork/write/wait/exit。 */

static void run(char c);               /* 本工程从VA 0启动，因此main必须排在首个函数。 */

/* 函数作用：创建 A/B 两个计算进程并等待它们全部结束。 */
int                                      /* 用户程序main按约定返回整数状态。 */
main(void)                               /* 创建两个CPU密集子进程并观察抢占。 */
{                                        /* 开始抢占可视化测试。 */
  if (fork() == 0)                       /* 第一次fork的子分支负责字符A。 */
    run('A');                          /* 第一个子进程持续输出 A。 */
  if (fork() == 0)                       /* 第二次fork的子分支负责字符B。 */
    run('B');                          /* 第二个子进程持续输出 B。 */
  wait(0);                             /* 回收第一个结束的子进程。 */
  wait(0);                             /* 回收剩余子进程。 */
  printf("\nPASS: alt preemption\n"); /* 能交错并返回即证明抢占链路工作。 */
  exit(0);                             /* 交还 Shell。 */
}                                        /* 正常路径已通过exit离开用户程序。 */

/* 函数作用：持续计算并间歇输出同一个字符，制造可见的抢占轨迹。 */
static void                              /* 子负载以exit结束，因此不返回值。 */
run(char c)                              /* 反复计算并输出给定进程标识字符。 */
{                                        /* 开始单个子进程的CPU密集负载。 */
  int i;                               /* 外层输出轮次。 */
  for (i = 0; i < 40; i++) {             /* 生成40个可观察输出采样点。 */
    volatile int d;                    /* volatile 防止编译器删除计算循环。 */
    for (d = 0; d < 20000000; d++)       /* 在两次输出之间保留足够抢占时间。 */
      ;                                /* 保持在用户态，等待时钟抢占。 */
    write(1, &c, 1);                   /* 输出一次当前进程标识。 */
  }                                      /* 完成当前子进程的40轮负载。 */
  exit(0);                             /* 让父进程通过 wait 回收。 */
}                                        /* exit为noreturn，正常不会执行到函数末尾。 */
