        # S 态中断入口。进入时已经在当前进程的内核栈上，只需保存可能被
        # C 函数破坏的调用者保存寄存器，处理完成后用 sret 返回原位置。
        .globl kerneltrap               # 声明 C 函数 kerneltrap 是跨文件可见符号。
        .globl kernelvec                # 导出 S 态内核中断入口供 stvec 使用。
        .align 4                        # 按 16 字节对齐入口地址。
        # 入口作用：保存 S 态内核现场，调用 kerneltrap 后恢复并返回。
kernelvec:                              # 内核处于 S 态时发生 trap 从这里进入。
        addi sp, sp, -256               # 在当前可信内核栈上预留 256 字节现场保存区。
        sd ra,   0(sp)                  # 保存返回地址寄存器 ra。
        sd gp,  16(sp)                  # 保存全局指针寄存器 gp。
        sd t0,  32(sp)                  # 保存调用者保存临时寄存器 t0。
        sd t1,  40(sp)                  # 保存调用者保存临时寄存器 t1。
        sd t2,  48(sp)                  # 保存调用者保存临时寄存器 t2。
        sd a0,  72(sp)                  # 保存第 1 个参数及返回值寄存器 a0。
        sd a1,  80(sp)                  # 保存第 2 个参数寄存器 a1。
        sd a2,  88(sp)                  # 保存第 3 个参数寄存器 a2。
        sd a3,  96(sp)                  # 保存第 4 个参数寄存器 a3。
        sd a4, 104(sp)                  # 保存第 5 个参数寄存器 a4。
        sd a5, 112(sp)                  # 保存第 6 个参数寄存器 a5。
        sd a6, 120(sp)                  # 保存第 7 个参数寄存器 a6。
        sd a7, 128(sp)                  # 保存第 8 个参数寄存器 a7。
        sd t3, 216(sp)                  # 保存调用者保存临时寄存器 t3。
        sd t4, 224(sp)                  # 保存调用者保存临时寄存器 t4。
        sd t5, 232(sp)                  # 保存调用者保存临时寄存器 t5。
        sd t6, 240(sp)                  # 保存调用者保存临时寄存器 t6。

        call kerneltrap                 # 在现场安全保存后调用 C 语言内核 trap 分发函数。

        ld ra,   0(sp)                  # 恢复中断前的返回地址寄存器 ra。
        ld gp,  16(sp)                  # 恢复中断前的全局指针寄存器 gp。
        ld t0,  32(sp)                  # 恢复中断前的临时寄存器 t0。
        ld t1,  40(sp)                  # 恢复中断前的临时寄存器 t1。
        ld t2,  48(sp)                  # 恢复中断前的临时寄存器 t2。
        ld a0,  72(sp)                  # 恢复中断前的参数寄存器 a0。
        ld a1,  80(sp)                  # 恢复中断前的参数寄存器 a1。
        ld a2,  88(sp)                  # 恢复中断前的参数寄存器 a2。
        ld a3,  96(sp)                  # 恢复中断前的参数寄存器 a3。
        ld a4, 104(sp)                  # 恢复中断前的参数寄存器 a4。
        ld a5, 112(sp)                  # 恢复中断前的参数寄存器 a5。
        ld a6, 120(sp)                  # 恢复中断前的参数寄存器 a6。
        ld a7, 128(sp)                  # 恢复中断前的参数寄存器 a7。
        ld t3, 216(sp)                  # 恢复中断前的临时寄存器 t3。
        ld t4, 224(sp)                  # 恢复中断前的临时寄存器 t4。
        ld t5, 232(sp)                  # 恢复中断前的临时寄存器 t5。
        ld t6, 240(sp)                  # 恢复中断前的临时寄存器 t6。
        addi sp, sp, 256                # 释放现场保存区，让 sp 回到中断发生前的位置。
        sret                             # 按 sepc/sstatus 返回被中断的 S 态代码。
